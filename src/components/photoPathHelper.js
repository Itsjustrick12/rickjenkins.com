// Grab ALL pictures in the repo
const images = import.meta.glob('/src/**/*.{png,jpg,jpeg,webp,PNG,JPG,JPEG,WEBP}', {
    eager: true,
    query: '?url',
    import: 'default'
});

// Get the path that coverts well for viter
export function getAssetPath(path) {
    if (!path) return '';

    // Convert Windows separators to URL-style separators
    let normalized = path.replace(/\\/g, '/');

    // Resolve paths written relative to a Markdown file in src/posts/
    if (normalized.startsWith('../')) {
        normalized = '/src/' + normalized.slice(3);
    }

    // Convert paths starting with src/
    if (normalized.startsWith('src/')) {
        normalized = '/' + normalized;
    }

    // Return the URL generated by Vite for deployment
    return images[normalized] ?? path;
}
